"""
make_report_tables.py - turns results/*.json|csv into LaTeX tables (report/tables/*.tex).

Called at the end of run_all.py, so every number in the report's tables is
produced by code and re-generated by the one-command run.
"""

from __future__ import annotations

import json
import os

import pandas as pd

RES, OUT = "results", "report/tables"


def esc(s: str) -> str:
    return str(s).replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def pm(v, d=3):
    return f"${v[0]:.{d}f}\\pm{v[1]:.{d}f}$"


def write(name, text):
    os.makedirs(OUT, exist_ok=True)
    with open(f"{OUT}/{name}.tex", "w", encoding="utf-8") as fh:
        fh.write(text)


SHORT = {  # short display names for the models
    "Ours: decision tree": "Ours: decision tree",
    "sklearn DecisionTreeRegressor": "sklearn tree",
    "sklearn DecisionTreeClassifier": "sklearn tree",
    "Ours: Pegasos linear SVM": "Ours: Pegasos (linear)",
    "sklearn SGDClassifier (hinge, averaged)": "sklearn SGD (hinge, avg.)",
    "sklearn SGDClassifier (hinge, no averaging)": "sklearn SGD (hinge, plain)",
    "Ours: Pegasos + RFF (RBF) SVM": "Ours: Pegasos + RFF (RBF)",
}


def short(n):
    if n.startswith("Ours: RFF SVM"):
        return "Ours: RFF-RBF (15k subs.)"
    if n.startswith("sklearn SVC"):
        return "sklearn SVC-RBF (15k subs.)"
    if n.startswith("Baseline: always"):
        return "Baseline: majority class"
    if n.startswith("Baseline: train-mean"):
        return "Baseline: train mean"
    return SHORT.get(n, n)


def main() -> None:
    R = json.load(open(f"{RES}/results.json", encoding="utf-8"))
    D = R["data"]

    # ---- cleaning log
    labels = ["Raw rows", "Repeated scrapes of one listing", "Non-residential (land, garage, office, commercial)",
              "Area outside 15--1000 m$^2$", "Price outside 5k--10M AZN", "Price/m$^2$ outside 200--15k AZN",
              "Coordinates outside Azerbaijan", "Near-duplicate re-posts"]
    rows = [f"{lab} & {c['before'] - c['after']:,} & {c['after']:,} \\\\" for lab, c in zip(labels, R["cleaning_log"])]
    rows[0] = f"{labels[0]} & -- & {R['cleaning_log'][0]['after']:,} \\\\"
    write("cleaning", "\\begin{tabular}{@{}lrr@{}}\n\\toprule\nStep & Removed & Left \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- dataset summary
    write("data", "\\begin{tabular}{@{}lr@{}}\n\\toprule\nProperty & Value \\\\\n\\midrule\n"
          f"Rows (after cleaning) & {D['rows']:,} \\\\\nFeatures used & {D['n_features']} \\\\\n"
          f"Train / Val / Test split & {D['n_train']:,} / {D['n_val']:,} / {D['n_test']:,} \\\\\n"
          f"Tier threshold (train median) & {D['tier_threshold_azn']:,.0f} AZN \\\\\n"
          f"Premium share (train/val/test) & {100 * D['premium_share']['train']:.1f} / {100 * D['premium_share']['val']:.1f} / {100 * D['premium_share']['test']:.1f}\\,\\% \\\\\n"
          f"Median / mean price & {D['price_median']:,.0f} / {D['price_mean']:,.0f} AZN \\\\\n"
          "\\bottomrule\n\\end{tabular}\n")

    # ---- Task A results
    cvA = R["cv_taskA"]
    rows = []
    for name, m in R["test_taskA"].items():
        cv = cvA.get(name)
        ci = f"[{m['rmse_azn_ci_low'] / 1e3:.0f}, {m['rmse_azn_ci_high'] / 1e3:.0f}]"
        rows.append(f"{esc(short(name))} & {m['rmse_log']:.3f} & {m['r2_log']:.3f} & {m['rmse_azn'] / 1e3:.0f} {ci} & "
                    f"{m['mae_azn'] / 1e3:.1f} & " + (pm(cv['rmse_log'], 3) if cv else "--") + " \\\\")
    write("results_a", "\\begin{tabular}{@{}lccccc@{}}\n\\toprule\nModel & RMSE$_{\\log}$ & $R^2_{\\log}$ & RMSE (k AZN) [95\\% CI] & MAE (k AZN) & CV RMSE$_{\\log}$ \\\\\n\\midrule\n"
          + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- Task B results
    cvB = R["cv_taskB"]
    rows = []
    for name, m in R["test_taskB"].items():
        cv = cvB.get(name)
        f1 = f"{m['f1']:.3f}" + (f" [{m['f1_ci_low']:.3f}, {m['f1_ci_high']:.3f}]" if "f1_ci_low" in m else "")
        rows.append(f"{esc(short(name))} & {m['accuracy']:.3f} & {m['precision']:.3f} & {m['recall']:.3f} & {f1} & {m['roc_auc']:.3f} & "
                    f"{m['pr_auc']:.3f} & " + (pm(cv['f1'], 3) if cv else "--") + f" & {m['fit_s']:.2f} \\\\")
    write("results_b", "\\begin{tabular}{@{}lccccccc c@{}}\n\\toprule\nModel & Acc. & Prec. & Rec. & F1 [95\\% CI] & ROC-AUC & PR-AUC & CV F1 & Fit (s) \\\\\n\\midrule\n"
          + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- agreement with sklearn by depth
    A = pd.read_csv(f"{RES}/agreement_by_depth.csv")
    infty = r"$\infty$"
    rows = [f"{infty if r.max_depth < 0 else int(r.max_depth)} & {100 * r.cls_pred_agree:.2f} & {int(r.cls_leaves_ours)}/{int(r.cls_leaves_sk)} & "
            f"{100 * r.reg_pred_agree:.2f} & {int(r.reg_leaves_ours)}/{int(r.reg_leaves_sk)} \\\\" for r in A.itertuples()]
    write("agreement", "\\begin{tabular}{@{}rcccc@{}}\n\\toprule\n & \\multicolumn{2}{c}{Task B (Gini)} & \\multicolumn{2}{c}{Task A (MSE)} \\\\\n"
          "max\\_depth & same pred. (\\%) & leaves ours/sk & same pred. (\\%) & leaves ours/sk \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- stopping rules
    S = pd.read_csv(f"{RES}/tree_stopping_rules.csv")
    rows = [f"{esc(r.setting)} & {int(r.depth)} & {int(r.leaves)} & {r.val_f1:.3f} \\\\" for r in S.itertuples()]
    write("stopping", "\\begin{tabular}{@{}lrrr@{}}\n\\toprule\nSetting (Gini, Task B) & Depth & Leaves & Val F1 \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- SVM lambda sweep
    L = pd.read_csv(f"{RES}/svm_lambda_sweep.csv")
    rows = [f"{r.lambda_:.0e} & {int(r.epochs)} & {r.margin_width:.3f} & {int(r.n_support):,} & {r.train_objective:.3f} & "
            f"{'yes' if r.converged else 'no'} & {r.val_f1:.3f} & {r.val_auc:.3f} \\\\" for r in L.itertuples()]
    write("svm_lambda", "\\begin{tabular}{@{}rrrrrrcc@{}}\n\\toprule\n$\\lambda$ & Epochs & Margin & \\#SV & $J$ & Conv. & Val F1 & Val AUC \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    print(f"   [tables] written to {OUT}/")


if __name__ == "__main__":
    main()
